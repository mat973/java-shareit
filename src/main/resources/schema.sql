-- Сначала создаем таблицы БЕЗ циклических ссылок
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(512) NOT NULL,
  CONSTRAINT pk_user PRIMARY KEY (id),
  CONSTRAINT UQ_USER_EMAIL UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  description VARCHAR(512) NOT NULL,
  requester_id BIGINT NOT NULL,
  created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_requests PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(255) NOT NULL,
  description VARCHAR(512),
  is_available BOOLEAN DEFAULT TRUE,
  owner_id BIGINT NOT NULL,
  request_id BIGINT,
  CONSTRAINT pk_items PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS bookings (
   id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP NOT NULL,
    item_id BIGINT REFERENCES items (id),
    booker_id BIGINT  REFERENCES users (id),
    status VARCHAR(50) NOT NULL,
      CONSTRAINT pk_bookings PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS comments (
   id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   text VARCHAR(512) NOT NULL,
    item_id BIGINT REFERENCES items (id),
    author_id  BIGINT  REFERENCES users (id),
    created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_comments PRIMARY KEY (id)
);


ALTER TABLE requests DROP CONSTRAINT IF EXISTS fk_requests_requester;
ALTER TABLE requests ADD CONSTRAINT fk_requests_requester
  FOREIGN KEY (requester_id) REFERENCES users (id);

ALTER TABLE items DROP CONSTRAINT IF EXISTS fk_items_owner;
ALTER TABLE items ADD CONSTRAINT fk_items_owner
  FOREIGN KEY (owner_id) REFERENCES users (id);

ALTER TABLE items DROP CONSTRAINT IF EXISTS fk_items_request;
ALTER TABLE items ADD CONSTRAINT fk_items_request
  FOREIGN KEY (request_id) REFERENCES requests (id);